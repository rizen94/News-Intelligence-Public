def build_pack(repo, project_name, limit_rows=8):
    timestamp = datetime.datetime.now().isoformat()

    agents = repo / "AGENTS.md"
    if not agents.exists():
        raise ValueError(f"AGENTS.md not found in {repo}")

    title = "NEWS INTELLIGENCE SYSTEM" if "News Intelligence" in project_name else "HOME AI LAB STACK"

    # Gather data
    purpose_line = ""
    readme = repo / "README.md"
    if readme.exists():
        raw = readme.read_text(encoding="utf-8")
        m = re.search(r"^# .*\n\n(.*?)(?=\n\n|\Z)", raw, re.DOTALL)
        if m:
            purpose_line = m.group(1).strip()[:500]

    guardrails = host_guardrails(agents)
    intent = project_intent(agents)
    terminology_rows = extract_table_rows(agents, "Terminology (Use Consistently)")
    entry_points_rows = extract_table_rows(agents, "Entry Points")

    # Architecture snippets
    arch_parts = []
    sys_md = repo / "docs" / "SYSTEM_OVERVIEW.md"
    if sys_md.exists():
        for h in ["Route Map", "Routes", "API routes"]:
            raw = extract_section(sys_md, h)
            if raw:
                arch_parts.append(f"### {h}\n{raw[:2000]}\n")
                break

    pipe_md = repo / "docs" / "PIPELINE_AND_AUTOMATION.md"
    if pipe_md.exists():
        raw = extract_section(pipe_md, "Pipeline Phases (order of operations)")
        if raw:
            arch_parts.append(f"### Pipeline Phases\n{raw[:1500]}\n")

    # Database
    db_info = None
    db_md = repo / "docs" / "DATABASE.md"
    if db_md.exists():
        for h in ["Connection", "Database Configuration", "Config"]:
            raw = extract_section(db_md, h)
            if raw:
                db_info = raw[:1500]
                break

    # Status
    status_text = None
    status_md = repo / "PROJECT_STATUS.md"
    if status_md.exists():
        for h in ["Open items", "Known Issues", "Hotlist", "TODO"]:
            raw = extract_section(status_md, h)
            if raw:
                status_text = raw[:2000]
                break

    # Key Decisions / ADRs
    dec_text = None
    dec_md = repo / "docs" / "KEY_DECISIONS.md"
    if dec_md.exists():
        raw = extract_section(dec_md, "") or dec_md.read_text(encoding="utf-8")[:3000]
        dec_text = raw[:2000]

    # MemPalace audit
    mp_audit = None
    mp_md = repo / "docs" / "MEMPALACE_NI.md"
    if mp_md.exists():
        raw = extract_section(mp_md, "Audit snapshot")
        if raw and len(raw.strip()) > 10:
            mp_audit = raw[:600]

    # Environment
    env_text = None
    env_md = repo / "docs" / "SETUP_ENV_AND_RUNTIME.md"
    if env_md.exists():
        for h in ["Environment", ".env", "Configuration"]:
            raw = extract_section(env_md, h)
            if raw:
                env_text = raw[:1500]
                break

    # -- Compile sections --
    s = []  # list of section strings (will be numbered sequentially)

    # Section 1: Purpose
    p1 = f"**{title}**\n\n"
    if purpose_line:
        p1 += purpose_line + "\n\n"
    if intent and "not found" not in intent:
        p1 += f"**Intent:** {intent}\n\n"
    if guardrails:
        p1 += "**Host Guardrails:**\n```text\n" + guardrails + "\n```\n"
    s.append(p1)

    # Section 2: Terminology
    if terminology_rows:
        rows = [r for r in terminology_rows[:limit_rows]]
        s.append("\n".join(rows))

    # Section 3: Entry Points
    if entry_points_rows:
        rows = [r for r in entry_points_rows[:limit_rows]]
        s.append("\n".join(rows))

    # Section 4: Architecture
    if arch_parts:
        s.append("Architecture & Flow\n" + "\n".join(arch_parts))

    # Section 5: Database
    if db_info:
        s.append(f"Database\n{db_info}\n")

    # Section 6: File Tree
    tree = scan_tree(repo)
    s.append(tree)

    # Section 7: Status
    if status_text:
        s.append(status_text)

    # Section 8: Key Decisions
    if dec_text:
        s.append(dec_text)

    # Section 8b: MemPalace Audit
    if mp_audit:
        s.append(f"MemPalace Audit\n{mp_audit}\n")

    # Section N: Environment
    if env_text:
        s.append(env_text)

    # Section N+1: Git Activity
    s.append(git_log_summary(repo))

    # Full log
    full = git_log_full(repo)
    s.append(f"\n```\n{full[:5000]}\n```")

    # Docs-impact sweep — flag docs that reference changed code
    sweep = docs_impact_sweep(repo)
    if sweep["impacted_docs"]:
        s.append(format_impact_sweep(sweep))

    # Footer
    footer = (
        "---\n\n"
        "### How to use this pack\n\n"
        "1. **Start here:** Purpose & Identity -> Entry Points -> Architecture\n"
        "2. **Dive deeper:** Use entry point paths to navigate; read docs/ referenced in architecture\n"
        "3. **For code changes:** Check PROJECT_STATUS.md open items first\n"
        f"4. **After working:** Run `python scripts/context_pack.py --project {project_name}` to regenerate\n\n"
        "### What's included (live)\n\n"
        "- Live file tree scan (not stale CODEBASE_MAP)\n"
        "- AGENTS.md key sections: terminology, entry points\n"
        "- PROJECT_STATUS open items\n"
        "- Key architecture docs (top N chars from each)\n"
        "- DATABASE config summary\n"
        "- Recent git activity (30-day window)\n"
        "- **Docs impact sweep** — flag docs that reference changed code\n"
        "- Key decisions / ADRs if available\n\n"
        "### What's NOT included\n\n"
        "- MemPalace drawers (too large; use mempalace_search instead)\n"
        "- Full codebase contents (use mempalace pack_codebase for agent context)\n"
        "- All docs (use [00-index.md](00-index.md) to navigate the rest)"
    )

    # -- Build output --
    parts = [f"# {title} -- Context Pack"]

    for i, sec in enumerate(s, start=1):
        parts.append(f"\n## {i}. {' '.join(sec.split(chr(10))[0][:60])}")
        parts.append(sec)

    parts.append("\n" + footer)

    return HEADER.format(timestamp=timestamp) + "\n".join(parts)


# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Compress project docs & codebase into one onboarding context file."
    )
    parser.add_argument("--project", "-p", default="News Intelligence",
                        help="Project name (News Intelligence | HomeLab-AI-Stack)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print summary only; don't write files.")
    parser.add_argument("--limit-entries", "-l", type=int, default=8,
                        help="Max table rows per section (default 8)")
    parser.add_argument("--output", "-o", type=str, default=None,
                        help="Output path (default: docs/ONBOARDING_CONTEXT.md)")
    args = parser.parse_args()

    candidates = {
        "News Intelligence": PROJECTS_ROOT / "News Intelligence",
        "HomeLab-AI-Stack": PROJECTS_ROOT / "HomeLab-AI-Stack",
    }

    if args.project in candidates:
        repo = candidates[args.project]
    elif Path(args.project).exists():
        repo = Path(args.project).resolve()
    else:
        print(f"Unknown project '{args.project}'. Try one of: {', '.join(candidates.keys())}",
              file=sys.stderr)
        sys.exit(1)

    if not (repo / "AGENTS.md").exists():
        print(f"AGENTS.md not found in {repo}. Not a valid project root.", file=sys.stderr)
        sys.exit(1)

    pack = build_pack(repo, args.project, limit_rows=args.limit_entries)

    if args.dry_run:
        print(f"=== Context Pack Summary (project={args.project}) ===")
        for line in pack.split("\n"):
            if line.startswith("## "):
                name = line[3:].strip()
                idx_start = pack.find(line) + len(line)
                idx_end = pack.find("\n## ", idx_start)
                if idx_end == -1:
                    idx_end = len(pack)
                count = len(pack[idx_start:idx_end].strip())
                print(f"  {name}: ~{count} chars")
        total_lines = len(pack.split("\n"))
        print(f"\nTotal: {len(pack)} chars, {total_lines} lines (~{total_lines // 60} pages)")
        return

    docs_dir = repo / "docs"
    docs_dir.mkdir(parents=True, exist_ok=True)
    out_path = Path(args.output) if args.output else docs_dir / "ONBOARDING_CONTEXT.md"
    out_path.write_text(pack, encoding="utf-8")
    print(f"Context pack written -> {out_path.resolve()} ({len(pack)} chars)")

    # Also write the documentation index (00-index.md).
    vault_dir = repo / "vault" if (repo / "vault").exists() else None
    idx = build_nav_index(repo, str(vault_dir) if vault_dir else None)
    nav_md = nav_index_to_markdown(idx, str(repo))
    index_path = docs_dir / "00-index.md"
    index_path.write_text(nav_md, encoding="utf-8")
    print(f"Documentation index written -> {index_path.resolve()} ({len(nav_md)} chars)")


if __name__ == "__main__":
    main()
