def extract_section(path, heading):
    """Extract content under ## Heading from a markdown file."""
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    pattern = rf"^## {re.escape(heading)}\n(.*?)(?=\n## |\Z)"
    match = re.search(pattern, text, re.DOTALL | re.MULTILINE)
    if not match:
        return None
    return match.group(1).strip()


def extract_table_rows(path, heading):
    """Extract table rows under ## heading."""
    text = extract_section(path, heading)
    if not text:
        return []
    return [l for l in text.split("\n") if "|" in l and not all(c in "|-" for c in l)]


def project_intent(agents):
    raw = extract_section(agents, "Project Intent")
    if not raw:
        return "(not found)"
    paras = [p.strip() for p in raw.split("\n\n") if p.strip()]
    return "\n".join(paras[:3])


def host_guardrails(agents):
    raw = extract_section(agents, "HOST GUARDRAILS (read first)")
    if not raw:
        return None
    lines = [l.strip() for l in raw.split("\n") if l.strip()]
    return "\n".join(lines[:8])


