DOC_EXTENSIONS = {".md", ".txt", ".rst", ".yaml", ".yml"}


def _is_doc_file(filepath):
    """Return True if *filepath* looks like a doc/markup/config file."""
    return filepath.suffix.lower() in DOC_EXTENSIONS


def docs_impact_sweep(repo_dir, days=DRIFT_WINDOW_DAYS):
    """Scan changed files from git, grep docs for cross-references.

    Returns a dict with "changed" and "impacted_docs".
    """
    repo = Path(repo_dir)
    changed_paths = git_changed_paths(repo, days)

    if not changed_paths:
        return {"changed": [], "impacted_docs": []}

    # Filter to code/config files worth grepping for
    code_paths = [
        p for p in changed_paths
        if _is_doc_file(Path(p)) or any(c in p for c in ("api/", "web/src/", "scripts/", "docs/"))
    ]

    # Smart keyword selection:
    # - Few changes → full-path + targeted stems
    # - Many changes → only exact full-path (no stems — too noisy)
    # Always skip overly broad/common names
    common_stems = {"main", "test", "config", "read", "setup", "app", "core", "util"}
    if len(code_paths) > 50:
        keywords = list(set(code_paths))
    else:
        extra_kws = set()
        for cp in code_paths:
            base = Path(cp).stem
            rel_dir = Path(cp).parent.name
            if len(base) > 4 and base.lower() not in common_stems:
                extra_kws.add(base)
            # Also use directory name as a keyword (e.g., "collectors", "domains")
            if len(rel_dir) > 3 and rel_dir != "config" and rel_dir != "specs":
                extra_kws.add(rel_dir)
        keywords = list(set(code_paths)) + list(extra_kws)
    impacted_docs = []

    for subdir in ["docs", "vault"]:
        doc_dir = repo / subdir
        if not doc_dir.exists():
            continue
        for md_file in sorted(doc_dir.rglob("*.md")):
            text = md_file.read_text(encoding="utf-8")
            found_refs, line_count = [], 0
            for kw in keywords:
                matches = [l for l in text.splitlines() if kw.lower() in l.lower()]
                if matches:
                    found_refs.append(kw)
                    line_count += len(matches)
            if found_refs:
                relpath = str(md_file.relative_to(repo))
                impacted_docs.append({"doc": relpath, "references": sorted(set(found_refs)), "lines": line_count})

    impacted_docs.sort(key=lambda x: x["lines"], reverse=True)
    return {"changed": changed_paths, "impacted_docs": impacted_docs}


def format_impact_sweep(sweep_result):
    """Format a docs-impact sweep dict into markdown.

    Truncation behavior for cross-reference results:
    - >10 matched docs: group by directory, show top 10 sorted by line count
    - <=10 matched docs: show full list, capped at 5 items with a "more flagged" note
    """
    lines = ["## Docs Impact Sweep", ""]

    if not sweep_result["changed"]:
        return "\n".join(lines + ["No code changes detected — no docs flagged."])

    lines.append(f"**{len(sweep_result['changed'])} changed paths** in the last DRIFT_WINDOW_DAYS days:")
    lines.append("")

    code_changed = [p for p in sweep_result["changed"] if not _is_doc_file(Path(str(p)))]
    doc_changed = [p for p in sweep_result["changed"] if _is_doc_file(Path(str(p)))]

    if code_changed:
        lines.append("### Changed code/config:")
        lines.append("")
        # Group by top-level directory when there are many changes
        dirs = {}
        for cp in code_changed:
            root = cp.split("/")[0]
            dirs.setdefault(root, []).append(cp)
        if len(dirs) <= 20:
            for d in sorted(dirs.keys())[:15]:
                files = sorted(dirs[d])[:3]
                lines.append(f"- **`{d}/**` — {len(dirs[d])} files")
                for f in files:
                    lines.append(f"  - `{f}`")
            if len(dirs) > 15:
                lines.append(f"- ... (+{len(dirs)-15} more top-level dirs)")
        else:
            # Too many directories — just show counts
            for d in sorted(dirs.keys(), key=lambda x: -len(dirs[x]))[:10]:
                lines.append(f"- **`{d}/**` — {len(dirs[d])} files")
        lines.append("")

    if doc_changed:
        lines.extend(["### Changed docs (directly modified):", ""])
        for dp in sorted(doc_changed)[:10]:
            lines.append(f"- `{dp}`")
        if len(doc_changed) > 10:
            lines.append(f"- ... ({len(doc_changed)-10} more)")
        lines.append("")

    impacted = sweep_result["impacted_docs"]
    
    if not impacted:
        lines.extend(["### Cross-references:", "No docs found referencing changed code paths."])
    elif len(impacted) > 10:
        # Too many matches — likely false positives from broad changes. Summarize only top hits.
        top = sorted(impacted, key=lambda x: -x["lines"])[:10]

        # Group by directory for overview
        dirs = {}
        for d in impacted:
            root = os.path.basename(os.path.dirname(d["doc"]))
            dirs.setdefault(root, 0)
            dirs[root] += 1
        
        lines.append(f"### Docs with cross-references ({len(impacted)} flagged — top 10 shown):")
        lines.append("")
        
        # Directory-level summary
        if len(dirs) > 5:
            lines.append("**Matched by directory:**")
            for d, c in sorted(dirs.items(), key=lambda x: -x[1])[:8]:
                lines.append(f"- `{d}/` — {c} files")
            lines.append("")
        
        # Top individual docs
        lines.append("**Most matched docs:**")
        for doc_entry in top:
            ref_list = sorted(doc_entry["references"])
            lines.append(f"- **[{doc_entry['doc']}]** (~{doc_entry['lines']} refs)")
            for ref in ref_list[:3]:
                lines.append(f"  - `{ref}`")
            if len(ref_list) > 3:
                lines.append(f"  - ... (+{len(ref_list)-3} more)")
        
        lines.append("")
        lines.append(f"> **ℹ️  {len(impacted)} doc file(s) match changed code — "
                      f"top {10} shown. Review only if changes affect your area.**")
    else:
        # Few enough to show fully
        lines.append(f"### Docs with cross-references ({len(impacted)} flagged):")
        lines.append("")
        for doc_entry in impacted[:5]:
            lines.append(f"- **[{doc_entry['doc']}]** (~{doc_entry['lines']} refs)")
            ref_list = sorted(doc_entry["references"])
            for ref in ref_list[:3]:
                lines.append(f"  - `{ref}`")
            if len(ref_list) > 3:
                lines.append(f"  - ... (+{len(ref_list)-3} more)")
        if len(impacted) > 5:
            lines.append(f"- ... (+{len(impacted)-5} more flagged docs)")
        
        lines.append("")
        lines.append("> **⚠️  All flagged docs should be reviewed for accuracy.**")

    return "\n".join(lines)


