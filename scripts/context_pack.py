def git_log_summary(repo_dir, days=DRIFT_WINDOW_DAYS):
    """Show recent commits touching docs/configs (top 15)."""
    since_dt = datetime.date.today() - datetime.timedelta(days=days)
    raw = run(
        ["git", "log", f"--since={since_dt.isoformat()}",
         "--pretty=format:%h | %ad | %s"], cwd=repo_dir)
    if not raw:
        return "(no commits in last 30 days)"

    lines = []
    seen = set()
    doc_kw = {"agent", "context_pack", "docs/", "readme", "agents.md",
              "project_status", "key_decisions", "architecture", "pipeline",
              "coding_style", "database", "setup_env"}
    for line in raw.split("\n"):
        short = line.strip()
        if not short or short in seen:
            continue
        seen.add(short)
        if any(kw in short.lower() for kw in doc_kw):
            lines.append(f"- `{short[:90]}`")
        elif len(lines) < 3:
            # Show some recent non-doc commits too (top 3)
            lines.append(f"- `{short[:90]}`")
        if len(lines) >= 15:
            break
    return "\n".join(lines) if lines else "(no relevant commits)"


def git_log_full(repo_dir, days=DRIFT_WINDOW_DAYS):
    """Full compact git log for reference."""
    since_dt = datetime.date.today() - datetime.timedelta(days=days)
    raw = run(
        ["git", "log", f"--since={since_dt.isoformat()}",
         "--pretty=format:%h | %ad | %s"], cwd=repo_dir)
    return raw or "(no commits)"


def git_changed_paths(repo_dir, days=DRIFT_WINDOW_DAYS):
    """Return list of file paths changed in the last `days`."""
    since_dt = datetime.date.today() - datetime.timedelta(days=days)
    raw = run(
        ["git", "log", f"--since={since_dt.isoformat()}",
         "--name-only", "--pretty=format:"], cwd=repo_dir)
    if not raw:
        return []
    seen = set()
    paths = []
    for p in raw.splitlines():
        p = p.strip()
        if p and p not in seen:
            seen.add(p)
            paths.append(p)
    return paths


