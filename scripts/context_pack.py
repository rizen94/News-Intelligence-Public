def _filename_to_display(path_str):
    """Return a readable name for a markdown file."""
    name = os.path.basename(path_str)
    if name == "README.md":
        return "README"
    base = name[:-3]  # strip .md
    parts = re.split(r'[-_]', base)
    return " ".join(p.capitalize() for p in parts)


def _file_purpose_preview(filepath):
    """Grab the first sentence after ## heading as a one-liner description."""
    text = filepath.read_text(encoding="utf-8") if filepath.exists() else ""
    m = re.search(r"^## .*?\n\n(.*?)(?=\\n\\n|\\Z)", text, re.DOTALL | re.MULTILINE)
    if not m:
        return "(no summary)"
    line = m.group(1).strip().split("\n")[0]
    return line[:120].rstrip(".")


def _categorize_file(relpath):
    """Return the category key for a given relative file path string."""
    rel_lower = relpath.lower()
    basename = os.path.basename(relpath)
    if basename in _ALWAYS_SEPARATE and "_archive" not in relpath:
        return None
    if "_archive" in relpath:
        return "Archived documentation"
    for cat_keys, keywords in _NAV_CATEGORIES.items():
        if any(kw.lower() in rel_lower for kw in keywords):
            return cat_keys
    return None


def build_nav_index(repo_dir, vault_dir=None):
    """Build an auto-categorized navigation index for docs/ + vault/.

    Returns a dict:
        {
            "heading": str,
            "entries": [(category_or_None, relpath, display_name, preview)],
            "vault_files": [(relpath, display, preview)],
            "timestamp": str,
        }
    """
    timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M")
    all_entries = []  # (cat_or_None, relpath, display, preview)

    # Scan docs/
    docs_dir = repo_dir / "docs"
    if docs_dir.exists():
        for md_file in sorted(docs_dir.rglob("*.md")):
            relpath = str(md_file.relative_to(repo_dir))
            key = _categorize_file(relpath)
            display = _filename_to_display(relpath)
            preview = _file_purpose_preview(md_file)
            all_entries.append((key, relpath, display, preview))

    # Scan vault/ if provided.
    vault_files_cat = []
    if vault_dir and vault_dir.exists():
        for vf in sorted(vault_dir.rglob("*.md")):
            relpath = str(vf.relative_to(repo_dir))
            display = _filename_to_display(relpath)
            preview = _file_purpose_preview(vf)
            vault_files_cat.append((relpath, display, preview))

    return {
        "heading": f"Documentation navigation — generated {timestamp}",
        "entries": all_entries,
        "vault_files": vault_files_cat,
        "timestamp": timestamp,
    }


