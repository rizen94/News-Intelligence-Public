def scan_tree(repo_dir, max_depth=2, max_children=6):
    """Compact live file tree for key directories."""
    lines = ["```"]

    def _walk(d, indent=0):
        children = [x for x in sorted(d.iterdir(), key=lambda x: (not x.is_dir(), x.name)) if d.exists()]
        # Limit breadth
        if len(children) > max_children * 3:
            dirs = [c for c in children if c.is_dir()][:max_children]
            files = [c for c in children if not c.is_dir() and c.suffix in ('.py', '.md', '.yaml', '.yml', '.json', '.ts', '.tsx')]
            for f in sorted(files, key=lambda x: x.name)[:8]:
                lines.append(f"{'  ' * (indent+1)}- {f.name}")
            remaining_dirs = len([c for c in children if c.is_dir()]) - max_children
            remaining_files = len(files) - 8
            if remaining_dirs > 0:
                lines.append(f"{'  ' * (indent+1)}- ... (+{remaining_dirs} dirs, {remaining_files} files)")
        else:
            for item in children:
                if item.is_dir():
                    lines.append(f"{'  ' * indent}: {item.name}/")
                    _walk(item, indent + 1)
                else:
                    lines.append(f"{'  ' * (indent+1)}- {item.name}")

    for subdir in ["api", "web/src", "scripts", "docs", "configs"]:
        p = repo_dir / subdir
        if p.exists() and p.is_dir():
            _walk(p)

    lines.append("```")
    return "\n".join(lines)


