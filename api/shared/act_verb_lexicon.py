ACT_VERB_RE = re.compile(
    r"\b(" + "|".join(re.escape(v) for v in sorted(ACT_VERBS, key=len, reverse=True)) + r")\b",
    re.I,
)


def text_has_act_verb(text: str | None) -> bool:
    return bool(ACT_VERB_RE.search(text or ""))


def count_act_verbs(text: str | None) -> int:
    return len(ACT_VERB_RE.findall(text or ""))
